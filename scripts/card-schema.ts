import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { join } from 'node:path';
import * as v from 'valibot';
import { toJsonSchema, type ConversionConfig, type JsonSchema } from '@valibot/to-json-schema';
import { authoredCardSchema, cardTranslationSchema } from '../packages/content/src/compiler';
import type { FactionDefinition } from '../packages/content/src/factionDefinition';
import type { SetDefinition } from '../packages/content/src/setDefinition';
import { abilities } from '../packages/extensions/src';
import { abilityParameterSchema } from '../packages/extensions/src/definition';

const config:ConversionConfig={
  target:'draft-07',typeMode:'input',ignoreActions:['trim'],
  overrideSchema:({valibotSchema})=>{
    // Enumerated record keys are optional, but should also autocomplete as properties.
    if(valibotSchema.type!=='record')return;
    const record=valibotSchema as v.GenericSchema & {key:{type:string;options:readonly string[]};value:v.GenericSchema};
    if(record.key.type!=='picklist')return;
    const value=toJsonSchema(record.value,config);delete value.$schema;
    return {type:'object',properties:Object.fromEntries(record.key.options.map(key=>[key,structuredClone(value)])),additionalProperties:false};
  },
};
const ref=(name:string):JsonSchema=>({$ref:`#/definitions/${name}`});
const condition=(type:string):JsonSchema=>({properties:{type:{const:type}},required:['type']});
const bindingContains=(field:string,id:string):JsonSchema=>({properties:{[field]:{contains:{properties:{id:{const:id}},required:['id']}}},required:[field]});

/** Enum lists come from source metadata; parameter schemas come from the runtime ability definitions. */
export function buildCardJsonSchema(factions:readonly FactionDefinition[],sets:readonly SetDefinition[]):JsonSchema{
  const named=factions.map(f=>f.id).filter(id=>id!=='neutral').sort();
  const schema=toJsonSchema(authoredCardSchema(named),config),properties=schema.properties!;
  delete properties.art;delete properties.animation;
  schema.$id='urn:realms-of-varhyr:card';
  schema.title='Realms of Varhyr card';
  schema.description='An authored assets/cards/<card-name>/data.json definition. Artwork comes from data.png; animation optionally comes from data.webm.';
  schema.$comment='Generated by npm run schema:cards and card imports. Edit the Valibot definitions, factions, sets or abilities instead.';
  schema.additionalProperties=false;
  schema.required=[...schema.required!.filter(key=>key!=='art'),'set'];
  properties.$schema={type:'string',description:'Editor schema reference; ignored by the game importer.',default:'../../schemas/card.schema.json'};
  properties.id={type:'string',pattern:'^[a-z0-9]+(?:-[a-z0-9]+)*$',description:'Stable card ID, independent of the folder or translated name.'};
  properties.deckLimitKey={...properties.id as JsonSchema,description:'Shared copy-limit identity. Usually the card ID; reprints can share this key.'};
  properties.name={type:'string',pattern:'\\S',description:'English card name. The German name goes in data.de.json.'};
  properties.set={type:'string',enum:sets.map(set=>set.id).sort(),description:'Release ID from assets/sets/.',default:'foundations'};
  properties.lore={type:'string',description:'Optional flavor text. Rules text comes from the registered ability descriptions.'};
  properties.factions={...properties.factions as JsonSchema,uniqueItems:true,description:'Use named factions, ["neutral"], or [] for a neutral card. Neutral cannot be combined with a named faction.'};
  properties.subtypes={type:'array',items:{type:'string',pattern:'\\S'},description:'Freeform subtypes, e.g. human, elf, leader or unicorn. They are not a closed enum; German labels live in the shared dictionary (packages/ui/src/i18n/de.json), not per card.'};
  (properties.rarity as JsonSchema).description='Booster rarity; independent of the legendary copy-limit flag.';
  (properties.legendary as JsonSchema).description='One copy per deck and collection, regardless of rarity.';
  const cost=properties.cost as JsonSchema;
  cost.additionalProperties=false;
  (cost.properties!.generic as JsonSchema).description='Cost payable with any energy.';
  (cost.properties!.factions as JsonSchema).description='Faction-specific costs. neutral, generic and primal are not valid cost keys.';
  const stats=properties.stats as JsonSchema;
  stats.additionalProperties=false;
  (stats.properties!.energyOutputs as JsonSchema).description='Alternative printed production pools: choose one when channeling or receiving death energy. One pool with several keys produces all of them. [] means no printed production; Primal is an ability.';

  const ids=Object.keys(abilities).sort(),definitions:Record<string,JsonSchema>={};
  for(const id of ids){
    const ability=abilities[id],params=toJsonSchema(abilityParameterSchema(ability),config);
    delete params.$schema;
    params.additionalProperties=false;
    const energy=(params.properties as Record<string,JsonSchema>|undefined)?.energy;
    if(energy)energy.enum=[...named,'neutral'];
    definitions[`ability-${id}`]={type:'object',title:ability.name,description:ability.description,
      properties:{id:{const:id},params},required:['id','params'],additionalProperties:false};
  }
  const bindings=(allowed:string[]):JsonSchema=>({type:'object',properties:{id:{type:'string',enum:allowed},params:{type:'object'}},required:['id','params'],oneOf:allowed.map(id=>ref(`ability-${id}`))});
  definitions.ability=bindings(ids);
  definitions['spell-ability']=bindings(ids.filter(id=>!abilities[id].activate));
  definitions['spell-operation']=bindings(ids.filter(id=>!!abilities[id].cast));
  definitions['bulwark-ability']=bindings(ids.filter(id=>!abilities[id].activationEnergy));
  schema.definitions=definitions;
  properties.abilities={type:'array',items:ref('ability'),description:'Registered abilities. Parameters depend on the selected ID.',default:[]};
  properties.cast={type:'array',items:ref('spell-operation'),minItems:1,description:'Spell operations resolved in list order.'};
  (properties.timing as JsonSchema).uniqueItems=true;

  schema.allOf=[
    {if:condition('spell'),then:{required:['cast','timing'],properties:{stats:false,abilities:{items:ref('spell-ability')}}},else:{required:['stats'],properties:{cast:false,timing:false}}},
    {if:condition('bulwark'),then:{properties:{stats:{properties:{energyOutputs:{maxItems:0}}},abilities:{items:ref('bulwark-ability')}}}},
    {if:{properties:{factions:{contains:{const:'neutral'}}},required:['factions']},then:{properties:{factions:{maxItems:1}}}},
    ...ids.flatMap(id=>{
      const faction=abilities[id].faction;
      return faction?[{if:{anyOf:[bindingContains('abilities',id),bindingContains('cast',id)]},then:{properties:{factions:faction==='neutral'?{enum:[[],['neutral']]}:{contains:{const:faction}}}}}]:[];
    }),
  ];
  return schema;
}

/** The translated fields of a card, authored in assets/cards/<card-name>/data.<language>.json. */
export function buildCardTranslationJsonSchema():JsonSchema{
  const schema=toJsonSchema(cardTranslationSchema,config),properties=schema.properties!;
  schema.$id='urn:realms-of-varhyr:card-translation';
  schema.title='Realms of Varhyr card translation';
  schema.description='The translated fields of one card, in assets/cards/<card-name>/data.<language>.json (currently data.de.json). Type, subtypes, rarity and rules text are translated statically, not per card.';
  schema.$comment='Generated by npm run schema:cards and card imports. Edit the Valibot definitions instead.';
  schema.additionalProperties=false;
  properties.$schema={type:'string',description:'Editor schema reference; ignored by the game importer.',default:'../../schemas/card-translation.schema.json'};
  properties.name={type:'string',pattern:'\\S',description:'The card name in this language.'};
  properties.lore={type:'string',description:'The flavor text in this language. Provide it whenever the English card has lore.'};
  return schema;
}

async function writeIfChanged(directory:string,file:string,schema:JsonSchema):Promise<boolean>{
  const path=join(directory,file),data=JSON.stringify(schema,null,2)+'\n';
  try{if(await readFile(path,'utf8')===data)return false;}catch(error){if((error as NodeJS.ErrnoException).code!=='ENOENT')throw error;}
  await mkdir(directory,{recursive:true});
  const temporary=join(directory,`.card-schema-${randomUUID()}.tmp`);
  await writeFile(temporary,data);await rename(temporary,path);
  return true;
}
/** Only touch the generated schemas when they changed; atomic writes are safe under parallel build/test imports. */
export async function writeCardJsonSchema(root:string,factions:readonly FactionDefinition[],sets:readonly SetDefinition[]):Promise<boolean>{
  const directory=join(root,'assets/schemas');
  const card=await writeIfChanged(directory,'card.schema.json',buildCardJsonSchema(factions,sets));
  const translation=await writeIfChanged(directory,'card-translation.schema.json',buildCardTranslationJsonSchema());
  return card||translation;
}
